// Writes src/build-info.js: which commit this deploy was built from. Run it before `wrangler deploy`
// (Cloudflare dashboard > Workers & Pages > peikoff-net > Settings > Build > Build command: `node tools/build-info.mjs`).
// Why a generated module: Workers Builds exposes WORKERS_CI_COMMIT_SHA to the build only, not to the running Worker,
// and a [vars] entry would be written by the build too. A file the build writes and wrangler bundles needs no dashboard variable
// and cannot be wiped by a deploy. Usage: node tools/build-info.mjs [--out path]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outArg = process.argv.indexOf("--out");
const out = outArg > 0 ? resolve(process.argv[outArg + 1]) : resolve(root, "src/build-info.js");

const git = (...args) => { try { return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim(); } catch { return ""; } };
const fromCi = (process.env.WORKERS_CI_COMMIT_SHA || "").trim();                          // set by Cloudflare Workers Builds
const commit = /^[0-9a-f]{40}$/i.test(fromCi) ? fromCi.toLowerCase() : git("rev-parse", "HEAD");
const [date = "", ...subject] = commit ? git("show", "-s", "--format=%cI%n%s", commit).split("\n") : [];
let version = ""; try { version = String(JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")).version || ""); } catch { /* no package.json version: none is shown */ }

const info = {
  commit,
  date,
  message: subject.join(" ").slice(0, 200),
  version,
  builtAt: new Date().toISOString(),
  dirty: !fromCi && !!git("status", "--porcelain", "--untracked-files=no"),        // local deploys only: uncommitted changes went out
};

writeFileSync(out, `// Generated by tools/build-info.mjs at build time. Do not edit; do not commit a real value.\nexport default ${JSON.stringify(info, null, 2)};\n`);
if (!outArg) git("update-index", "--skip-worktree", "src/build-info.js");          // keep a local build's values out of git add -A
console.log(`build-info: ${commit ? commit.slice(0, 7) : "no commit found"}${info.dirty ? " (uncommitted changes)" : ""}${version ? ` v${version}` : ""}`);
